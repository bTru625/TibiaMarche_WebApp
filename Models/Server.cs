using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;

namespace TibiaMarche_WebApp.Models
{
    public class Server
    {
        private int _id;                    // autogenerated in the DB
        private string _name = string.Empty;
        private bool _isActive = true;
        private Server? _mergedInto = null;
        private ServerType _type;

        // Parameterless constructor (model binding / Firestore)
        public Server()
        {
        }

        public Server(string name, ServerType type)
        {
            _name = name;
            _isActive = true;
            _type = type;
        }

        public int Id
        {
            get { return _id; }
            set { _id = value; }
        }

        public string Name
        {
            get { return _name; }
            set { _name = value; }
        }

        public bool IsActive
        {
            get { return _isActive; }
            set { _isActive = value; }
        }

        public Server? MergedInto
        {
            get { return _mergedInto; }
            set { _mergedInto = value; }
        }

        public ServerType Type
        {
            get { return _type; }
            set { _type = value; }
        }

        public string NameAndType
        {
            get { return $"{_name} ({_type.DisplayName()})"; }
        }

        public void MergeInto(Server server)
        {
            _mergedInto = server;
            _isActive = false;
        }

        public bool IsMerged()
        {
            return _mergedInto != null;
        }
    }
}